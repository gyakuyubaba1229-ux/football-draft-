export function getLocalizedTacticName(tactic: TacticType, lang: Language): string {
  return TACTIC_LABELS[tactic]?.[lang] || TACTIC_LABELS[tactic].ja;
}

export function getLocalizedManagerName(manager: Manager, lang: Language): string {
  if (lang === 'ja') return manager.nameJa;
  if (lang === 'es') return manager.nameEs;
  return manager.nameEn;
}

export function getLocalizedManagerNationality(manager: Manager, lang: Language): string {
  if (lang === 'ja') return manager.nationalityJa;
  if (lang === 'es') return manager.nationalityEs;
  return manager.nationalityEn;
}

export function getLocalizedManagerAchievements(manager: Manager, lang: Language): string[] {
  if (lang === 'ja') return manager.achievementsJa;
  if (lang === 'es') return manager.achievementsEs;
  return manager.achievementsEn;
}

