// Validate uniqueness & bounds (0-99)
export const MANAGERS_DATABASE: Manager[] = (() => {
  const seenIds = new Set<string>();
  const seenNames = new Set<string>();
  const result: Manager[] = [];

  for (const mgr of RAW_MANAGERS) {
    const key = mgr.name.toLowerCase().trim();
    if (seenIds.has(mgr.id) || seenNames.has(key)) continue;
    seenIds.add(mgr.id);
    seenNames.add(key);

    const clampedTactics = {
      possession: Math.max(0, Math.min(99, mgr.tactics.possession)),
      shortCounter: Math.max(0, Math.min(99, mgr.tactics.shortCounter)),
      longCounter: Math.max(0, Math.min(99, mgr.tactics.longCounter)),
      sideAttack: Math.max(0, Math.min(99, mgr.tactics.sideAttack)),
      longBall: Math.max(0, Math.min(99, mgr.tactics.longBall)),
    };
    const maxAffinity = Math.min(
      99,
      Math.max(
        clampedTactics.possession,
        clampedTactics.shortCounter,
        clampedTactics.longCounter,
        clampedTactics.sideAttack,
        clampedTactics.longBall
      )
    );

    result.push({
      ...mgr,
      tactics: clampedTactics,
      maxAffinity,
    });
  }

  return result;
})();

/**
 * Picks `count` unique real managers randomly for the Manager Draft.
 */
export function drawManagerCandidates(count: number = 3): Manager[] {
  const shuffled = [...MANAGERS_DATABASE].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
