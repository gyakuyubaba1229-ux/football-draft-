/**
 * Check if a player is a verified Ballon d'Or winner
 */
export function getBallonDorWinner(player: Player): BallonDorInfo | null {
  const normPerson = String(player.personId).trim().toLowerCase();
  if (BALLON_DOR_WINNERS[normPerson]) {
    return BALLON_DOR_WINNERS[normPerson];
  }

  // Check by name matching if personId differs
  for (const key of Object.keys(BALLON_DOR_WINNERS)) {
    const item = BALLON_DOR_WINNERS[key];
    if (
      item.playerName.toLowerCase() === player.playerName.toLowerCase() ||
      item.nameJa === player.nameJa ||
      normPerson.includes(key)
    ) {
      return item;
    }
  }

  return null;
}

