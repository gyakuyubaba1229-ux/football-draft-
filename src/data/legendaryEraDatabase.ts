/**
 * Helper to find Ballon d'Or winner combination from the dedicated SPECIAL_BALLON_DOR_PLAYERS
 * Ensuring OVR 100+ Ballon d'Or players ONLY come from special presentation.
 */
export function findBallonDorCombination(
  mode: GameMode,
  excludePlayerIds: string[] = [],
  excludePersonIds: string[] = []
): { player: Player; ballonDorInfo: BallonDorInfo } | null {
  const eligible = SPECIAL_BALLON_DOR_PLAYERS.filter((p) => {
    if (excludePlayerIds.includes(p.playerId)) return false;
    if (excludePersonIds.includes(p.personId)) return false;
    
    // In J1 mode, prefer J1 Ballon d'Or icons (Zico, Iniesta, Stoichkov, Dunga) if available
    if (mode === 'j1') {
      const isJ1 = ['kashima_antlers', 'vissel_kobe', 'kashiwa_reysol', 'jubilo_iwata', 'nagoya_grampus'].includes(p.clubId);
      return isJ1;
    }
    // In Europe mode, match European giants
    const isEurope = !['kashima_antlers', 'vissel_kobe', 'kashiwa_reysol', 'jubilo_iwata', 'nagoya_grampus'].includes(p.clubId);
    return isEurope;
  });

  const pool = eligible.length > 0 ? eligible : SPECIAL_BALLON_DOR_PLAYERS.filter(
    (p) => !excludePlayerIds.includes(p.playerId) && !excludePersonIds.includes(p.personId)
  );

  if (pool.length === 0) return null;
  const pickedPlayer = pool[Math.floor(Math.random() * pool.length)];
  const bInfo = getBallonDorWinner(pickedPlayer) || {
    personId: pickedPlayer.personId,
    playerName: pickedPlayer.playerName,
    nameJa: pickedPlayer.nameJa,
    nameEn: pickedPlayer.nameEn,
    nameEs: pickedPlayer.nameEs,
    winningYears: [pickedPlayer.joiningYear],
    totalWins: 1,
    iconicYear: pickedPlayer.joiningYear,
    clubAtWinJa: pickedPlayer.clubName,
    clubAtWinEn: pickedPlayer.clubName,
    clubAtWinEs: pickedPlayer.clubName,
    nationalityJa: pickedPlayer.nationalityJa,
    nationalityEn: pickedPlayer.nationalityEn,
    nationalityEs: pickedPlayer.nationalityEs,
    nationalityFlag: pickedPlayer.nationalityFlag,
    goldenSubtitleJa: `${pickedPlayer.joiningYear}年 バロンドール最高峰特別選手 OVR ${pickedPlayer.rating}`,
    goldenSubtitleEn: `${pickedPlayer.joiningYear} Ballon d\'Or Supreme Special Edition OVR ${pickedPlayer.rating}`,
    goldenSubtitleEs: `${pickedPlayer.joiningYear} Edición Especial Suprema Balón de Oro OVR ${pickedPlayer.rating}`,
    iconicFeatJa: `${pickedPlayer.clubName}で獲得した世界最高峰の栄誉（総合値 OVR ${pickedPlayer.rating}）`,
    iconicFeatEn: `World football supreme honor achieved at ${pickedPlayer.clubName} (OVR Rating ${pickedPlayer.rating})`,
    iconicFeatEs: `Máximo honor mundial logrado con el ${pickedPlayer.clubName} (Valoración OVR ${pickedPlayer.rating})`,
  };

  return { player: pickedPlayer, ballonDorInfo: bInfo };
}


